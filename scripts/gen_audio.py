#!/usr/bin/env python3
"""Generate every sound Prestwick plays (E5-S4). Stdlib only, deterministic.

Usage:
  python3 scripts/gen_audio.py            -> audio/*.wav (overwrites them)
  python3 scripts/gen_audio.py --list     -> print the sounds and their lengths, write nothing
  python3 scripts/gen_audio.py --out DIR  -> write into DIR instead of audio/

sfxr-style synthesis: oscillators (sine, triangle, square, noise), pitch slides, simple
one-pole filters and envelopes, mixed in Python and written as 16-bit mono PCM WAV at
22050 Hz. A fixed random seed per sound, so a rerun writes the same bytes and git shows no
change unless this script changed.

Readability first (pillar 2): each surface's shot sound is built to say the surface.
  strike_*  the club meeting the ball, by the lie: a crisp tee "tock", a clean fairway
            click, a dull grassy rough swish, a sand blast from a bunker, a hard clack off
            the cart path; `putt` a soft tap on the green.
  land_*    the ball's first touchdown, by the surface: a fairway thud, a rough muffle, a
            soft green pat, a sand "pff", a bouncing path clack.
  splash    water; `trees` a leaf rustle and a wooden knock; `oob` a falling two-tone
            "no"; `cup` a rattle and a plunk.
  praise / complaint   short stings for a guest's verdict.
  ambient   a 12 s wind and birdsong bed, loopable (a WAV `smpl` loop the importer reads).
  music     an 8 s loop, 120 BPM, I-vi-IV-V in C, loopable the same way.

Every file is original: generated by this script, no samples. See audio/LICENSE.md.
"""
from __future__ import annotations

import argparse
import math
import os
import random
import struct
import sys

RATE = 22050
TAU = 2.0 * math.pi


# --- building blocks -------------------------------------------------------------------

def n_samples(seconds: float) -> int:
    return int(round(seconds * RATE))


def silence(seconds: float) -> list[float]:
    return [0.0] * n_samples(seconds)


def osc(kind: str, f0: float, f1: float, seconds: float, rng: random.Random | None = None,
        duty: float = 0.5) -> list[float]:
    """An oscillator sliding exponentially from f0 to f1 Hz."""
    n = n_samples(seconds)
    out = [0.0] * n
    phase = 0.0
    for i in range(n):
        t = i / max(1, n - 1)
        f = f0 * (f1 / f0) ** t if f0 > 0 and f1 > 0 else f0 + (f1 - f0) * t
        phase = (phase + f / RATE) % 1.0
        if kind == "sine":
            v = math.sin(TAU * phase)
        elif kind == "tri":
            v = 4.0 * abs(phase - 0.5) - 1.0
        elif kind == "square":
            v = 1.0 if phase < duty else -1.0
        elif kind == "saw":
            v = 2.0 * phase - 1.0
        else:
            raise ValueError(kind)
        out[i] = v
    return out


def noise(seconds: float, rng: random.Random) -> list[float]:
    return [rng.uniform(-1.0, 1.0) for _ in range(n_samples(seconds))]


def lowpass(x: list[float], cutoff: float | list[float]) -> list[float]:
    """One-pole low-pass; `cutoff` in Hz, fixed or per sample."""
    out = [0.0] * len(x)
    y = 0.0
    for i, v in enumerate(x):
        c = cutoff[i] if isinstance(cutoff, list) else cutoff
        a = 1.0 - math.exp(-TAU * c / RATE)
        y += a * (v - y)
        out[i] = y
    return out


def highpass(x: list[float], cutoff: float) -> list[float]:
    low = lowpass(x, cutoff)
    return [a - b for a, b in zip(x, low)]


def bandpass(x: list[float], lo: float, hi: float) -> list[float]:
    return lowpass(highpass(x, lo), hi)


def env(x: list[float], attack: float, decay: float, sustain: float = 0.0,
        release: float = 0.0, curve: float = 2.0) -> list[float]:
    """Attack to 1, decay (power curve) to `sustain`, hold, then release over the last
    `release` seconds."""
    n = len(x)
    a = n_samples(attack)
    d = n_samples(decay)
    r = n_samples(release)
    out = [0.0] * n
    for i in range(n):
        if i < a:
            g = i / max(1, a)
        elif i < a + d:
            t = (i - a) / max(1, d)
            g = sustain + (1.0 - sustain) * (1.0 - t) ** curve
        else:
            g = sustain
        if r > 0 and i >= n - r:
            g *= (n - i) / r
        out[i] = x[i] * g
    return out


def gain(x: list[float], g: float) -> list[float]:
    return [v * g for v in x]


def mix(*parts: tuple[list[float], float]) -> list[float]:
    """Sum (signal, start seconds) pairs into one buffer."""
    length = max(n_samples(start) + len(sig) for sig, start in parts)
    out = [0.0] * length
    for sig, start in parts:
        o = n_samples(start)
        for i, v in enumerate(sig):
            out[o + i] += v
    return out


def normalize(x: list[float], peak: float) -> list[float]:
    m = max((abs(v) for v in x), default=0.0)
    return x if m <= 0.0 else [v * peak / m for v in x]


def fade_edges(x: list[float], seconds: float = 0.004) -> list[float]:
    """A short fade at both ends, so a one-shot never clicks."""
    n = min(n_samples(seconds), len(x) // 2)
    out = list(x)
    for i in range(n):
        g = i / n
        out[i] *= g
        out[-1 - i] *= g
    return out


def wrap_loop(x: list[float], length: int) -> list[float]:
    """Folds everything past `length` back onto the start, so a ringing tail plays over the
    loop's head and the loop point is seamless."""
    out = x[:length] + [0.0] * max(0, length - len(x))
    for i in range(length, len(x)):
        out[i % length] += x[i]
    return out


def crossfade_loop(x: list[float], length: int, fade: int) -> list[float]:
    """For a bed rendered `fade` samples longer than `length`: blends its tail into its head."""
    out = x[:length]
    for i in range(fade):
        g = i / fade
        out[i] = out[i] * g + x[length + i] * (1.0 - g)
    return out


# --- WAV ------------------------------------------------------------------------------

def write_wav(path: str, x: list[float], loop: bool = False) -> None:
    pcm = b"".join(struct.pack("<h", max(-32767, min(32767, int(round(v * 32767))))) for v in x)
    fmt = struct.pack("<HHIIHH", 1, 1, RATE, RATE * 2, 2, 16)
    chunks = b"fmt " + struct.pack("<I", len(fmt)) + fmt
    chunks += b"data" + struct.pack("<I", len(pcm)) + pcm
    if loop:
        # The `smpl` chunk: one forward loop over the whole file. Godot's WAV importer reads
        # it with its default loop mode (Detect From WAV), so the bed and the music loop.
        smpl = struct.pack("<9I", 0, 0, int(1e9 / RATE), 60, 0, 0, 0, 1, 0)
        smpl += struct.pack("<6I", 0, 0, 0, len(x) - 1, 0, 0)
        chunks += b"smpl" + struct.pack("<I", len(smpl)) + smpl
    data = b"WAVE" + chunks
    with open(path, "wb") as f:
        f.write(b"RIFF" + struct.pack("<I", len(data)) + data)


# --- the club on the ball -------------------------------------------------------------

def click(rng: random.Random, f: float, seconds: float, bright: float) -> list[float]:
    """The contact itself: a pitched ping plus a noise transient."""
    tone = env(osc("sine", f, f * 0.8, seconds), 0.0005, seconds)
    snap = env(highpass(noise(seconds * 0.5, rng), 2000.0), 0.0, seconds * 0.4, curve=4.0)
    return mix((tone, 0.0), (gain(snap, bright), 0.0))


def strike_tee(rng: random.Random) -> list[float]:
    # Off a peg, the cleanest strike: a bright high "tock" with a woody body and a swish.
    swish = env(bandpass(noise(0.12, rng), 1500.0, 5000.0), 0.08, 0.04, curve=1.0)
    body = env(osc("tri", 420.0, 300.0, 0.18), 0.0005, 0.18, curve=3.0)
    return mix((gain(swish, 0.25), 0.0), (click(rng, 2400.0, 0.09, 0.8), 0.08),
               (gain(body, 0.6), 0.08))


def strike_fairway(rng: random.Random) -> list[float]:
    # A clean click and a short brush of turf after it.
    turf = env(bandpass(noise(0.12, rng), 600.0, 2500.0), 0.003, 0.12, curve=2.0)
    body = env(osc("tri", 330.0, 260.0, 0.14), 0.0005, 0.14, curve=3.0)
    return mix((click(rng, 1800.0, 0.07, 0.6), 0.0), (gain(body, 0.45), 0.0),
               (gain(turf, 0.45), 0.01))


def strike_rough(rng: random.Random) -> list[float]:
    # Grass between club and ball: a dull, low click under a long swishy tear.
    grass = env(bandpass(noise(0.32, rng), 900.0, 3500.0), 0.02, 0.30, curve=1.5)
    tremor = [1.0 + 0.4 * math.sin(TAU * 38.0 * i / RATE) for i in range(len(grass))]
    grass = [a * b for a, b in zip(grass, tremor)]
    body = env(osc("tri", 240.0, 180.0, 0.12), 0.002, 0.12, curve=3.0)
    dull = lowpass(click(rng, 1100.0, 0.06, 0.3), 2500.0)
    return mix((gain(dull, 0.8), 0.0), (gain(body, 0.5), 0.0), (gain(grass, 0.7), 0.0))


def strike_bunker(rng: random.Random) -> list[float]:
    # A splash of sand: a long brown-noise blast with grit, the click almost buried.
    n = noise(0.42, rng)
    grit = [v if rng.random() < 0.35 else v * 0.2 for v in n]
    blast = env(lowpass(grit, 2600.0), 0.01, 0.40, curve=1.6)
    thump = env(osc("sine", 140.0, 70.0, 0.12), 0.002, 0.12)
    return mix((gain(blast, 1.0), 0.0), (gain(thump, 0.5), 0.0),
               (gain(click(rng, 1300.0, 0.04, 0.2), 0.25), 0.0))


def strike_cart_path(rng: random.Random) -> list[float]:
    # Club scraping concrete: a hard metallic clack with a short ring and a scrape.
    ring = env(osc("square", 2900.0, 2700.0, 0.20, duty=0.3), 0.0, 0.20, curve=3.0)
    ring2 = env(osc("sine", 4350.0, 4100.0, 0.16), 0.0, 0.16, curve=2.5)
    scrape = env(highpass(noise(0.10, rng), 3000.0), 0.0, 0.10, curve=2.0)
    return mix((click(rng, 2000.0, 0.05, 1.0), 0.0), (gain(ring, 0.25), 0.0),
               (gain(ring2, 0.25), 0.0), (gain(scrape, 0.5), 0.0))


def putt(rng: random.Random) -> list[float]:
    # On the green: a soft, small "tok".
    tok = env(osc("sine", 950.0, 880.0, 0.10), 0.001, 0.10, curve=3.0)
    knock = env(osc("tri", 480.0, 440.0, 0.08), 0.001, 0.08, curve=3.0)
    tick = env(highpass(noise(0.01, rng), 3000.0), 0.0, 0.01)
    return mix((tok, 0.0), (gain(knock, 0.5), 0.0), (gain(tick, 0.25), 0.0))


# --- the ball coming down -------------------------------------------------------------

def thud(f0: float, f1: float, seconds: float) -> list[float]:
    return env(osc("sine", f0, f1, seconds), 0.002, seconds, curve=2.5)


def land_fairway(rng: random.Random) -> list[float]:
    # A firm thud on short grass.
    grass = env(bandpass(noise(0.08, rng), 500.0, 2000.0), 0.002, 0.08)
    return mix((thud(190.0, 95.0, 0.16), 0.0), (gain(grass, 0.35), 0.0))


def land_rough(rng: random.Random) -> list[float]:
    # Swallowed by long grass: muffled, rustling, little thud.
    rustle = env(bandpass(noise(0.30, rng), 700.0, 3000.0), 0.01, 0.28, curve=1.4)
    return mix((gain(thud(140.0, 90.0, 0.12), 0.5), 0.0), (gain(rustle, 0.8), 0.0))


def land_green(rng: random.Random) -> list[float]:
    # A soft pat on the green, a touch higher than the fairway.
    pat = env(lowpass(noise(0.03, rng), 1800.0), 0.0, 0.03)
    return mix((thud(260.0, 150.0, 0.11), 0.0), (gain(pat, 0.4), 0.0))


def land_bunker(rng: random.Random) -> list[float]:
    # Into sand: a dead "pff", no bounce.
    pff = env(lowpass(noise(0.26, rng), 1400.0), 0.004, 0.24, curve=1.8)
    return mix((gain(pff, 1.0), 0.0), (gain(thud(110.0, 70.0, 0.10), 0.5), 0.0))


def land_cart_path(rng: random.Random) -> list[float]:
    # On concrete: two hard clacks, the ball bouncing on.
    def clack(level: float) -> list[float]:
        body = env(osc("square", 1600.0, 1500.0, 0.06, duty=0.25), 0.0, 0.06, curve=3.0)
        hit = env(highpass(noise(0.02, rng), 2500.0), 0.0, 0.02)
        return gain(mix((gain(body, 0.5), 0.0), (hit, 0.0)), level)
    return mix((clack(1.0), 0.0), (clack(0.55), 0.17), (clack(0.3), 0.29))


def splash(rng: random.Random) -> list[float]:
    # Water: a noise burst whose filter falls, then bubbles rising.
    n = n_samples(0.5)
    sweep = [5000.0 * (1.0 - i / n) ** 2 + 300.0 for i in range(n)]
    burst = env(lowpass(noise(0.5, rng), sweep), 0.004, 0.48, curve=1.5)
    parts: list[tuple[list[float], float]] = [(burst, 0.0)]
    for k in range(6):
        f = rng.uniform(500.0, 900.0)
        b = env(osc("sine", f, f * 1.8, 0.05), 0.003, 0.047)
        parts.append((gain(b, 0.25), 0.18 + k * 0.06 + rng.uniform(0.0, 0.03)))
    return mix(*parts)


def trees(rng: random.Random) -> list[float]:
    # Into the trees: a wooden knock off a branch, then leaves shaking.
    knock = env(osc("tri", 520.0, 380.0, 0.07), 0.0, 0.07, curve=3.0)
    knock2 = env(osc("tri", 610.0, 450.0, 0.05), 0.0, 0.05, curve=3.0)
    leaves = env(bandpass(noise(0.45, rng), 2500.0, 7000.0), 0.02, 0.43, curve=1.3)
    shake = [0.55 + 0.45 * math.sin(TAU * 17.0 * i / RATE) ** 2 for i in range(len(leaves))]
    leaves = [a * b for a, b in zip(leaves, shake)]
    return mix((knock, 0.0), (gain(knock2, 0.6), 0.09), (gain(leaves, 0.8), 0.02))


def oob(rng: random.Random) -> list[float]:
    # Out of bounds: a falling two-tone "no", the sfxr blip turned down.
    a = env(osc("square", 494.0, 494.0, 0.14, duty=0.5), 0.004, 0.0, 1.0, 0.03)
    b = env(osc("square", 330.0, 300.0, 0.26, duty=0.5), 0.004, 0.0, 1.0, 0.12)
    return lowpass(mix((a, 0.0), (b, 0.15)), 3000.0)


def cup(rng: random.Random) -> list[float]:
    # Holed: a rattle round the cup and a hollow plunk.
    parts: list[tuple[list[float], float]] = []
    for k, t in enumerate((0.0, 0.05, 0.09)):
        r = env(osc("sine", 2200.0 - k * 200.0, 2000.0 - k * 200.0, 0.03), 0.0, 0.03)
        parts.append((gain(r, 0.5 - k * 0.1), t))
    plunk = env(osc("sine", 300.0, 180.0, 0.22), 0.002, 0.22, curve=2.0)
    hollow = env(osc("sine", 620.0, 560.0, 0.18), 0.002, 0.18, curve=2.5)
    parts += [(plunk, 0.13), (gain(hollow, 0.3), 0.13)]
    return mix(*parts)


# --- stings -----------------------------------------------------------------------------

def note_hz(semis_from_a4: float) -> float:
    return 440.0 * 2.0 ** (semis_from_a4 / 12.0)


def praise(rng: random.Random) -> list[float]:
    # A bright rising major arpeggio (C6 E6 G6 C7), triangle with a square sparkle.
    parts: list[tuple[list[float], float]] = []
    for k, s in enumerate((3, 7, 10, 15)):
        f = note_hz(s)
        length = 0.10 if k < 3 else 0.28
        t = env(osc("tri", f, f, length), 0.004, length, curve=1.6)
        sq = env(osc("square", f * 2.0, f * 2.0, length, duty=0.25), 0.002, length, curve=3.0)
        parts.append((mix((t, 0.0), (gain(sq, 0.12), 0.0)), k * 0.075))
    return mix(*parts)


def complaint(rng: random.Random) -> list[float]:
    # A sagging "wah-wah": two falling square tones with a wobble, lower and duller.
    parts: list[tuple[list[float], float]] = []
    for k, (f0, f1) in enumerate(((311.0, 294.0), (262.0, 233.0))):
        length = 0.16 if k == 0 else 0.30
        n = n_samples(length)
        tone = osc("square", f0, f1, length, duty=0.35)
        wob = [1.0 + 0.25 * math.sin(TAU * 7.0 * i / RATE) for i in range(n)]
        tone = env([a * b for a, b in zip(tone, wob)], 0.006, 0.0, 1.0, length * 0.6)
        parts.append((lowpass(tone, 1600.0), k * 0.17))
    return mix(*parts)


# --- loops ------------------------------------------------------------------------------

def ambient(rng: random.Random) -> list[float]:
    """12 s of wind and birds. Every modulator runs a whole number of cycles in the loop,
    and the tail crossfades into the head, so the seam does not show."""
    length_s = 12.0
    fade_s = 0.5
    total = n_samples(length_s + fade_s)
    loop_n = n_samples(length_s)
    raw = [rng.uniform(-1.0, 1.0) for _ in range(total)]
    # Wind: low noise, its level and colour breathing over 12 s and 4 s.
    swell = [0.55 + 0.30 * math.sin(TAU * i / loop_n) + 0.15 * math.sin(TAU * 3 * i / loop_n + 1.0)
             for i in range(total)]
    cut = [350.0 + 250.0 * s for s in swell]
    wind = lowpass(lowpass(raw, cut), 900.0)
    wind = [w * s for w, s in zip(wind, swell)]
    wind = normalize(wind, 0.5)
    # Birds: a few short chirp phrases at fixed places, quiet and high.
    birds = [0.0] * total
    for start in (1.3, 4.6, 7.9, 10.2):
        o = n_samples(start + rng.uniform(-0.2, 0.2))
        for c in range(rng.randint(2, 4)):
            f0 = rng.uniform(2600.0, 3600.0)
            chirp = env(osc("sine", f0, f0 * rng.uniform(1.15, 1.4), 0.07), 0.006, 0.064,
                        curve=1.5)
            trill = [1.0 + 0.3 * math.sin(TAU * 45.0 * i / RATE) for i in range(len(chirp))]
            chirp = [a * b for a, b in zip(chirp, trill)]
            at = o + c * n_samples(0.11)
            for i, v in enumerate(chirp):
                if at + i < total:
                    birds[at + i] += v * 0.12
    bed = [w + b for w, b in zip(wind, birds)]
    return crossfade_loop(bed, loop_n, total - loop_n)


def music(rng: random.Random) -> list[float]:
    """8 s, 120 BPM, 16 beats: I-vi-IV-V in C. Triangle bass on the beat, soft pulse chords
    on the off-beats, a small triangle melody on top. Tails wrap into the head."""
    beat = 0.5
    bars = [(-21, (3, 7, 10)),   # C:  C3 bass; C5 E5 G5
            (-24, (0, 3, 7)),    # Am: A2;      A4 C5 E5
            (-28, (-4, 0, 3)),   # F:  F2;      F4 A4 C5
            (-26, (-2, 2, 5))]   # G:  G2;      G4 B4 D5
    melody = [15, 14, 10, 7, 12, 10, 7, 3, 8, 7, 3, 0, 5, 7, 10, 14]  # one note per beat
    loop_n = n_samples(16 * beat)
    parts: list[tuple[list[float], float]] = []
    for bar, (bass, chord) in enumerate(bars):
        for b in range(4):
            t = (bar * 4 + b) * beat
            f = note_hz(bass)
            bass_note = env(osc("tri", f, f, 0.42), 0.006, 0.36, 0.0, 0.0, curve=1.3)
            parts.append((gain(bass_note, 0.55), t))
            for s in chord:
                cf = note_hz(s)
                pad = env(osc("square", cf, cf, 0.18, duty=0.25), 0.004, 0.17, curve=2.0)
                parts.append((gain(lowpass(pad, 2200.0), 0.07), t + beat * 0.5))
            if (bar * 4 + b) % 2 == 0 or b == 3:
                mf = note_hz(melody[bar * 4 + b])
                lead = env(osc("tri", mf, mf, 0.45), 0.01, 0.40, 0.0, 0.0, curve=1.2)
                vib = [1.0 + 0.04 * math.sin(TAU * 5.0 * i / RATE) for i in range(len(lead))]
                parts.append((gain([a * v for a, v in zip(lead, vib)], 0.28), t))
    # A soft brushed hat on every off-beat.
    hat_rng = random.Random(rng.random())
    for k in range(16):
        h = env(highpass(noise(0.04, hat_rng), 6000.0), 0.0, 0.04, curve=3.0)
        parts.append((gain(h, 0.05), k * beat + beat * 0.5))
    return wrap_loop(mix(*parts), loop_n)


# --- the list ---------------------------------------------------------------------------

# name -> (builder, peak level, loops)
SOUNDS: dict[str, tuple] = {
    "strike_tee": (strike_tee, 0.85, False),
    "strike_fairway": (strike_fairway, 0.85, False),
    "strike_rough": (strike_rough, 0.8, False),
    "strike_bunker": (strike_bunker, 0.8, False),
    "strike_cart_path": (strike_cart_path, 0.8, False),
    "putt": (putt, 0.7, False),
    "land_fairway": (land_fairway, 0.75, False),
    "land_rough": (land_rough, 0.7, False),
    "land_green": (land_green, 0.65, False),
    "land_bunker": (land_bunker, 0.75, False),
    "land_cart_path": (land_cart_path, 0.75, False),
    "splash": (splash, 0.85, False),
    "trees": (trees, 0.8, False),
    "oob": (oob, 0.6, False),
    "cup": (cup, 0.8, False),
    "praise": (praise, 0.6, False),
    "complaint": (complaint, 0.55, False),
    "ambient": (ambient, 0.5, True),
    "music": (music, 0.6, True),
}


def render(name: str) -> list[float]:
    builder, peak, loops = SOUNDS[name]
    rng = random.Random(f"prestwick-{name}")
    x = normalize(builder(rng), peak)
    return x if loops else fade_edges(x)


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    p.add_argument("--out", default=os.path.join(root, "audio"))
    p.add_argument("--list", action="store_true")
    args = p.parse_args(argv)
    os.makedirs(args.out, exist_ok=True)
    for name, (_, _, loops) in SOUNDS.items():
        x = render(name)
        info = "%-18s %5.2f s%s" % (name, len(x) / RATE, "  loop" if loops else "")
        if not args.list:
            write_wav(os.path.join(args.out, name + ".wav"), x, loops)
        print(info)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
